public class Question3PrintNumbers {

    static void printNumbersUpToN(int n) {
        for (int i = 1; i <= n; i++) {
            System.out.println(i);
        }
    }

    public static void main(String[] args) {
        System.out.println("Register No: RA2511026011373");

        int n = 5;

        printNumbersUpToN(n);
    }
}